"""Bake expression-specific closed eyes without replacing brows, mouth or lower face.
Uses only original game face pixels; no generated skin or painted replacement mouth.
Coordinates are in the existing 530x800 rig space, with per-face fractional alignment.
"""
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np
from PIL import Image,ImageDraw

ROOT=Path(__file__).resolve().parents[1]
RIG=ROOT/'puppet/rig'
# Naturally closed/squinting faces and the deliberately comic shock stay unchanged.
NO_BLINK=[3496,3523,3625,3861,4006]
EYES=[[(253,89),(259,83),(269,81),(281,82),(290,88),(288,111),(254,111)],
      [(306,90),(310,84),(321,82),(333,83),(344,90),(344,112),(307,112)]]


def eye_mask(size,placement):
    # Supersample polygon coverage, but do not blur across the protected brow/mouth.
    factor=4
    mask=Image.new('L',(size[0]*factor,size[1]*factor))
    draw=ImageDraw.Draw(mask)
    for poly in EYES:
        points=[((x-placement['x'])*factor,(y-placement['y'])*factor) for x,y in poly]
        draw.polygon(points,fill=255)
    m=np.asarray(mask.resize(size,Image.Resampling.BOX)).copy()
    yy=np.arange(size[1])[:,None]+placement['y']
    m[np.broadcast_to((yy<81)|(yy>=113),m.shape)]=0
    return m


def close_eyes(source,closed,placement,closed_placement,face_id):
    if face_id in NO_BLINK:
        return source.copy()
    mask=eye_mask(source.size,placement)
    original=np.asarray(source.convert('RGBA')).copy()
    erased=original.copy()
    erased[:,:,3]=np.rint(original[:,:,3].astype('float32')*(1-mask/255)).astype('uint8')
    # Resample donor once using the exact fractional face offsets used by WebGL.
    donor=closed.transform(source.size,Image.Transform.AFFINE,
        (1,0,placement['x']-closed_placement['x'],0,1,placement['y']-closed_placement['y']),
        Image.Resampling.BICUBIC)
    pixels=np.asarray(donor).copy()
    yy=np.arange(source.height)[:,None]+placement['y']
    # Transplant just the dark closed lash lines, not donor eyebrows/blush/skin.
    luminance=pixels[:,:,:3].astype('float32').mean(axis=2)
    keep=(luminance<195)&(yy>=90)&(yy<=105)&(mask>0)
    pixels[:,:,3]=np.where(keep,np.rint(pixels[:,:,3].astype('float32')*mask/255),0).astype('uint8')
    result=np.asarray(Image.alpha_composite(Image.fromarray(erased),Image.fromarray(pixels))).copy()
    result[mask==0]=original[mask==0]
    return Image.fromarray(result)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=RIG)
    args=parser.parse_args();(args.output/'assets').mkdir(parents=True,exist_ok=True);(args.output/'js').mkdir(parents=True,exist_ok=True)
    cfg=json.loads((RIG/'js/assets.js').read_text(encoding='utf-8-sig').split('=',1)[1].strip().rstrip(';'))['baijie']
    closed=Image.open(RIG/'assets/baijie-face-3625.png').convert('RGBA')
    textures={};counts={};pins={}
    for key,f in cfg['faces'].items():
        src=RIG/f'assets/baijie-face-{key}.png';pins[src.name]=hashlib.sha256(src.read_bytes()).hexdigest()
        if int(key) in NO_BLINK:continue
        source=Image.open(src).convert('RGBA')
        image=close_eyes(source,closed,f,cfg['faces']['3625'],int(key))
        filename=f'baijie-blink-{key}.png';image.save(args.output/'assets'/filename)
        textures[key]=filename
        counts[key]=int(np.any(np.asarray(source)!=np.asarray(image),axis=2).sum())
    config={'baijie':{'noBlink':NO_BLINK,'textures':textures}}
    (args.output/'js/blink-assets.js').write_text('// Generated by tools/build_eye_blinks.py\nwindow.BLINK_ASSETS = '+json.dumps(config,indent=2)+';\n',encoding='utf-8')
    report={'changed_pixels':counts,'source_sha256':pins,'noBlink':NO_BLINK,'protected':'all pixels outside eye mask, brows y<81 and lower face y>=113'}
    (args.output/'eye-blink-report.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
    print(json.dumps(report,indent=2))

if __name__=='__main__':main()
