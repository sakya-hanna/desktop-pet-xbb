"""Split only the outer locks; do not synthesize clothing or change source assets.
Run from any directory: python tools/build_hair_layers.py [--output DIR]
Requires Pillow and numpy. Coordinates refer to the existing 530x800 baked body.
"""
import argparse
import json
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
# Boundaries run through the transparent gaps outside the arms and skirt.
PARTS = [
    dict(name='left', root=[199, 194], start=220, end=475, amplitude=0.055,
         poly=[[-1,170],[207,170],[195,205],[175,235],[145,280],
               [125,320],[119,340],[119,389],[123,420],[125,452],
               [122,497],[-1,497]]),
    dict(name='right', root=[412, 216], start=247, end=438, amplitude=0.065,
         poly=[[386,182],[413,195],[441,231],[466,271],[479,311],
               [479,351],[476,385],[472,413],[473,438],[531,450],[531,180]]),
]
# Explicit no-cut region: head, face, arms, hands, dress and legs.
PROTECTED = [(220,0),(375,0),(380,155),(388,220),(404,277),
             (419,314),(446,359),(466,397),(485,445),(455,510),
             (415,799),(155,799),(120,487),(127,447),(145,410),
             (158,389),(120,387),(119,360),(132,340),(155,323),
             (169,274),(190,220),(210,177),(220,140)]


def polygon(size, points):
    image = Image.new('1', size)
    ImageDraw.Draw(image).polygon([tuple(p) for p in points], fill=1)
    return np.asarray(image, dtype=bool)


def protected_mask(size):
    return polygon(size, PROTECTED)


def split_layers(source):
    if source.size != (530,800):
        raise ValueError('Expected the original 530x800 baked body; refusing to rescale masks')
    rgba = np.asarray(source.convert('RGBA')).copy()
    body = rgba.copy()
    protected = protected_mask(source.size)
    owned = np.zeros((source.height, source.width), dtype=bool)
    layers, stats = [], []
    for part in PARTS:
        mask = polygon(source.size, part['poly']) & ~protected & ~owned
        mask &= rgba[:,:,3] > 0
        owned |= mask
        layer = np.zeros_like(rgba)
        layer[mask] = rgba[mask]
        body[mask] = 0
        # Retain opaque donor pixels at the fixed root, never duplicate edge alpha.
        yy = np.arange(source.height)[:,None]
        keep = mask & (yy <= part['start'] + 12) & (rgba[:,:,3] == 255)
        body[keep] = rgba[keep]
        layers.append((part['name'],Image.fromarray(layer)))
        stats.append(dict(name=part['name'], pixels=int(mask.sum()), root_donor_pixels=int(keep.sum())))
    result = Image.fromarray(body)
    recomposed = result.copy()
    for _, layer in layers:
        recomposed.alpha_composite(layer)
    # Transparent RGB is immaterial to rendering but preserve it in the body too.
    empty = rgba[:,:,3] == 0
    body[empty] = rgba[empty]
    result = Image.fromarray(body)
    delta = np.abs(np.asarray(recomposed).astype('int16')-rgba.astype('int16'))
    delta[empty] = 0
    report = dict(parts=stats, reconstruction_max_error=int(delta.max()),
                  protected_pixels=int(protected.sum()), artificial_fill=False)
    if report['reconstruction_max_error']:
        raise ValueError('Rest reconstruction differs from original')
    return result, layers, report


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT/'puppet/rig')
    args=parser.parse_args()
    body,layers,report=split_layers(Image.open(ROOT/'puppet/rig/assets/baijie-body.png'))
    assets=args.output/'assets'; assets.mkdir(parents=True,exist_ok=True)
    body.save(assets/'baijie-layered-body.png')
    for name,im in layers: im.save(assets/f'baijie-outer-{name}.png')
    config={'baijie':dict(body='baijie-layered-body.png', layers=[
        {k:v for k,v in part.items() if k != 'poly'} | {'texture':f"baijie-outer-{part['name']}.png"}
        for part in PARTS])}
    (args.output/'js').mkdir(parents=True,exist_ok=True)
    (args.output/'js/hair-assets.js').write_text('// Generated by tools/build_hair_layers.py\nwindow.HAIR_ASSETS = '+json.dumps(config,indent=2)+';\n',encoding='utf-8')
    (args.output/'hair-layer-report.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
    print(json.dumps(report,indent=2))

if __name__=='__main__': main()
